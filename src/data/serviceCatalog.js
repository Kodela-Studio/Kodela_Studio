export function servicePageHref(id, pathname = "/packages") {
  const base =
    pathname.toLowerCase().replace(/\/$/, "") === "/nettsider"
      ? "/nettsider"
      : "/packages";
  return id ? `${base}?tjeneste=${encodeURIComponent(id)}` : base;
}

export function serviceEmailHref(name) {
  return `mailto:post@kodela.studio?subject=${encodeURIComponent(`Forespørsel om ${name.toLowerCase()}`)}`;
}
